"""
music_bitexact.py -- Integer-exact model of the HLS MUSIC + peak-search kernel (Tier 3).

Bit-true reference for hls/music. Input is the jacobi_evd output (72 words);
output is the two DOA estimates and the full MUSIC denominator.

Input   : 8 eigenvalues (raw Q7.25, unsorted), then V row-major (raw Q2.30)
Steering: B = Q^H A(grid), real, 8 x 181 ROM, ap_fixed<25,2> (Q2.22 stored in 25 bits)
Projection p_k(g) = e_k^T b(g)            exact sum, rounded once to Q3.29
Denominator d(g) = 8 - p_1(g)^2 - p_2(g)^2 exact, rounded once to Q5.27
                   (||b(g)||^2 = N = 8 exactly for a unit-modulus steering vector)
Peaks   : the K = 2 deepest strict local minima (d[g] < d[g-1], d[g] <= d[g+1]);
          if fewer than K exist, the smallest remaining d values fill in.
Refine  : delta = (d[g-1] - d[g+1]) / (2 (d[g-1] - 2 d[g] + d[g+1])) when the
          denominator is positive, one integer division, truncated toward zero.
Output  : 2 angles (raw Q16.16 degrees, ascending), then d(0..180) (raw Q5.27);
          183 words, TLAST on the last.
"""

from __future__ import annotations

import numpy as np

from doa_golden import MimoArray, real_steering_table

N = 8
K = 2
G = 181
GRID_DEG = np.arange(-90.0, 90.0 + 1e-9, 1.0)
GRID_OFFSET = 90                 # grid index g <-> angle g - 90 deg
V_FRAC = 30                      # eigenvectors Q2.30
B_FRAC = 22                      # steering ROM Q2.22 (25-bit signed)
P_FRAC = 29                      # projection Q3.29
D_FRAC = 27                      # denominator Q5.27
ANG_FRAC = 16                    # output angle Q16.16 degrees
N_OUT = K + G
NONE = -(1 << 31)                # unused angle slot (never produced for K = 2)


def _rnd(x: int, shift: int) -> int:
    return (x + (1 << (shift - 1))) >> shift


def steering_rom(array: MimoArray | None = None) -> np.ndarray:
    """Raw Q2.22 steering table, shape (N, G)."""
    b = real_steering_table(array or MimoArray(), GRID_DEG)
    return np.floor(b * 2 ** B_FRAC + 0.5).astype(np.int64)


B_ROM = steering_rom()


def top_k_indices(values, k: int):
    """Indices of the k largest values; ties keep the lower index (strict >)."""
    best = []
    for i, v in enumerate(values):
        best.append((v, i))
        best.sort(key=lambda t: (-t[0], t[1]))
        best = best[:k]
    return [i for _, i in best]


def music_denominator_raw(v_raw: np.ndarray, sel) -> list:
    """d(g) raw Q5.27 for the selected eigenvector columns."""
    d = []
    eight = 8 << (2 * P_FRAC)
    for g in range(G):
        s = 0
        for k in sel:
            acc = 0
            for n in range(N):
                acc += int(v_raw[n, k]) * int(B_ROM[n, g])
            p = _rnd(acc, V_FRAC + B_FRAC - P_FRAC)
            s += p * p
        d.append(_rnd(eight - s, 2 * P_FRAC - D_FRAC))
    return d


def _insert(best: list, d: int, g: int, k: int) -> list:
    """Keep the k smallest (d, g) pairs; strict < so earlier indices win ties."""
    best = best + [(d, g)]
    best.sort()
    return best[:k]


def peak_search_raw(d: list):
    """Selected grid indices and refined angles (raw Q16.16), ascending."""
    minima, overall = [], []
    for g in range(G):
        overall = _insert(overall, d[g], g, K)
        if 0 < g < G - 1 and d[g] < d[g - 1] and d[g] <= d[g + 1]:
            minima = _insert(minima, d[g], g, K)
    chosen = [g for _, g in minima]
    for _, g in overall:
        if len(chosen) >= K:
            break
        if g not in chosen:
            chosen.append(g)
    angles = []
    for g in chosen:
        delta = 0
        if 0 < g < G - 1:
            y0, y1, y2 = d[g - 1], d[g], d[g + 1]
            den = y0 - 2 * y1 + y2
            if den > 0:
                num = y0 - y2
                q = (abs(num) << ANG_FRAC) // (2 * den)
                delta = q if num >= 0 else -q
        angles.append(((g - GRID_OFFSET) << ANG_FRAC) + delta)
    return sorted(angles), chosen


def music_raw(d_raw_eig: np.ndarray, v_raw: np.ndarray):
    """jacobi_evd output -> (angles raw Q16.16, d raw Q5.27), as the HLS kernel."""
    sel = top_k_indices([int(x) for x in d_raw_eig], K)
    d = music_denominator_raw(v_raw, sel)
    angles, _ = peak_search_raw(d)
    lim = 1 << 31
    assert all(-lim <= x < lim for x in d), "32-bit range exceeded"
    return np.array(angles, dtype=np.int64), np.array(d, dtype=np.int64)


def angles_deg(angles_raw: np.ndarray) -> np.ndarray:
    return angles_raw.astype(float) * 2.0 ** -ANG_FRAC


def write_rom_header(path: str) -> None:
    """C header with the steering ROM (generated, so C and Python share one table)."""
    lines = [
        "// Generated by python/gen_music_vectors.py -- do not edit.",
        "// Real steering table B = Q^H A(grid), raw Q2.22 (ap_fixed<25,2>), [n][g],",
        "// grid -90..90 deg in 1-deg steps.",
        "#ifndef MUSIC_ROM_H",
        "#define MUSIC_ROM_H",
        f"static const int B_ROM[{N}][{G}] = {{",
    ]
    for n in range(N):
        lines.append("  {" + ",".join(str(int(x)) for x in B_ROM[n]) + "},")
    lines += ["};", "#endif", ""]
    with open(path, "w") as f:
        f.write("\n".join(lines))


def write_vectors_header(path: str, evd_frames: list) -> None:
    """Testbench vectors: 72 input words, 183 expected output words per frame."""
    lines = [
        "// Generated by python/gen_music_vectors.py -- do not edit.",
        "#ifndef MUSIC_VECTORS_H",
        "#define MUSIC_VECTORS_H",
        f"#define MUS_TV_FRAMES {len(evd_frames)}",
        f"static const int MUS_TV_IN[{len(evd_frames)}][{N + N * N}] = {{",
    ]
    outs = []
    for d_eig, v in evd_frames:
        words = np.concatenate([d_eig, np.asarray(v).ravel()])
        lines.append("  {" + ",".join(str(int(x)) for x in words) + "},")
        a, d = music_raw(d_eig, v)
        outs.append(np.concatenate([a, d]))
    lines.append("};")
    lines.append(f"static const int MUS_TV_OUT[{len(evd_frames)}][{N_OUT}] = {{")
    for o in outs:
        lines.append("  {" + ",".join(str(int(x)) for x in o) + "},")
    lines += ["};", "#endif", ""]
    with open(path, "w") as f:
        f.write("\n".join(lines))
